enum class AppTab(val title: String, val icon: ImageVector, val tag: String) {
    REST_STUDIO("REST Studio", Icons.Default.Send, "tab_rest_studio"),
    COMPOSE_HOOKS("Compose Hooks", Icons.Default.Widgets, "tab_compose_hooks"),
    PUBLISH_GUIDE("Publish & Docs", Icons.Default.MenuBook, "tab_publish_guide")
}

class MainActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()
        setContent {
            MyApplicationTheme {
                MainAppScreen()
            }
        }
    }
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun MainAppScreen() {
    var selectedTabIndex by rememberSaveable { mutableIntStateOf(0) }
    val currentTab = AppTab.entries[selectedTabIndex]

    Scaffold(
        modifier = Modifier.fillMaxSize(),
        topBar = {
            TopAppBar(
                title = {
                    Text(
                        text = "SimpleFetch",
                        fontWeight = FontWeight.Bold,
                        fontSize = 18.sp
                    )
                },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = MaterialTheme.colorScheme.surface,
                    titleContentColor = MaterialTheme.colorScheme.onSurface
                )
            )
        },
        bottomBar = {
            NavigationBar(
                containerColor = MaterialTheme.colorScheme.surface,
                modifier = Modifier.testTag("bottom_nav_bar")
            ) {
                AppTab.entries.forEachIndexed { index, tab ->
                    NavigationBarItem(
                        selected = selectedTabIndex == index,
                        onClick = { selectedTabIndex = index },
                        icon = { Icon(tab.icon, contentDescription = tab.title) },
                        label = { Text(tab.title, fontSize = 11.sp) },
                        modifier = Modifier.testTag(tab.tag)
                    )
                }
            }
        }
    ) { innerPadding ->
        Box(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
        ) {
            when (currentTab) {
                AppTab.REST_STUDIO -> RestStudioScreen()
                AppTab.COMPOSE_HOOKS -> ComposeDemosScreen()
                AppTab.PUBLISH_GUIDE -> PublishGuideScreen()
            }
        }
    }
}
